local function IsBot(player)
    return player.IsPlayerBot and player:IsPlayerBot()
end

-- ============================================================================
-- CLEAR REGISTRY
-- ============================================================================

--- Session cache: { set = { [dungeonId] = true }, count = n }. Loaded
--- synchronously once per session on first use (load-once read, glyph
--- module pattern); writes go through async CharDBExecute.
local function Clears(player)
    local cached = player:GetData(CLEARS_KEY)
    if cached then
        return cached
    end
    local clears = { set = {}, count = 0 }
    local q = CharDBQuery("SELECT dungeon FROM `" .. Constant.DB_NAME
        .. "`.`paragon_solo_clears` WHERE guid = " .. player:GetGUIDLow())
    if q then
        repeat
            local dungeon = q:GetUInt32(0)
            -- ids no longer in the allowlist don't count (or display)
            if DUNGEONS[dungeon] then
                clears.set[dungeon] = true
                clears.count = clears.count + 1
            end
        until not q:NextRow()
    end
    player:SetData(CLEARS_KEY, clears)
    return clears
end

-- ============================================================================
-- APPLY
-- ============================================================================

local RESIL_MODS = { "CRIT_TAKEN_MELEE", "CRIT_TAKEN_RANGED", "CRIT_TAKEN_SPELL" }

local function ApplyResil(player, amount, apply)
    for _, key in ipairs(RESIL_MODS) do
        player:ApplyRatingMod(Constant.STATISTICS.COMBAT_RATING[key], amount, apply)
    end
end

local function ReconcileCrit(player, want)
    local have = player:GetData(CRIT_KEY) or 0
    local present = player:HasAura(CRIT_SPELL)
    if want == have and present == (want > 0) then
        return
    end
    if present then
        player:RemoveAura(CRIT_SPELL)
    end
    if want > 0 then
        player:CastCustomSpell(player, CRIT_SPELL, true, want)
    end
    player:SetData(CRIT_KEY, want)
end

--- Grants every achievement the registry says is owed. Idempotent
--- (HasAchieved guard in the core); the era metas and capstone also
--- complete natively via their type-8 criteria — these calls are the
--- retro-grant / self-heal path. The core REFUSES grants in GM mode
--- (with a chat error per call), so skip entirely and let the next
--- GM-off reconcile catch up.
local function ReconcileAchievements(player, clears)
    if player:IsGM() then
        return
    end
    local metas = 0
    for era, ids in pairs(ERA) do
        local all = true
        for _, id in ipairs(ids) do
            if clears.set[id] then
                player:SetAchievement(ACH_BASE + id)
            else
                all = false
            end
        end
        if all then
            player:SetAchievement(ACH_META[era])
            metas = metas + 1
        end
    end
    if metas == 3 then
        player:SetAchievement(ACH_CAPSTONE)
    end
end

-- ============================================================================
-- PUSH (track tooltip, delta-suppressed)
-- ============================================================================

local function Push(player, count, resil, crit, force)
    local sig = count .. ";" .. resil .. ";" .. crit
    if not force and player:GetData(PUSHED_KEY) == sig then
        return
    end
    player:SetData(PUSHED_KEY, sig)
    player:SendServerResponse(PREFIX, 1, {
        count = count,
        total = TOTAL,
        resil = resil,
        crit = crit,
        -- clears until the next whole crit percent (nil when maxed)
        next_at = count < TOTAL
            and (math.floor(count / CLEARS_PER_CRIT) + 1) * CLEARS_PER_CRIT
            or nil,
    })
end

-- ============================================================================
-- RECONCILE
-- ============================================================================

local function Reconcile(player, force)
    -- account-gate contract: bots and sub-80 alts compute nothing. The
    -- fast path still lets a de-leveled character with stale stats fall
    -- through to the strip below (gem-module symmetry).
    local eligible = not IsBot(player) and player:GetLevel() >= 80
    if not eligible
            and (player:GetData(APPLIED_KEY) or 0) == 0
            and not player:HasAura(CRIT_SPELL) then
        return -- fast path: nothing applied, nothing to strip (every bot)
    end
    local paragon = eligible and player:GetData("Paragon") or nil
    local owed = paragon and paragon:GetLevel() >= MILESTONE
    local clears = eligible and Clears(player) or nil
    local count = clears and clears.count or 0
    local resil = owed and count * RESIL_PER_CLEAR or 0
    local crit = owed and math.floor(count / CLEARS_PER_CRIT) or 0

    local prev = player:GetData(APPLIED_KEY) or 0
    if prev ~= resil then
        if prev > 0 then
            ApplyResil(player, prev, false)
        end
        if resil > 0 then
            ApplyResil(player, resil, true)
        end
        player:SetData(APPLIED_KEY, resil)
    end
    -- always: also clears a stale relog-restored aura (death-persistent)
    ReconcileCrit(player, crit)
    if clears then
        -- achievements follow the registry, not the milestone
        if count > 0 then
            ReconcileAchievements(player, clears)
        end
        Push(player, count, resil, crit, force)
    end
end

local function SafeReconcile(player, force, label)
    local ok, err = pcall(Reconcile, player, force)
    if not ok then
        print("[Paragon] solo dungeon " .. label .. " error: " .. tostring(err))
    end
end

-- ============================================================================
-- COMPLETION HOOK (§1p)
-- ============================================================================

local function OnEncounterComplete(event, map, creditType, creditEntry, source, dungeonId)
    if not dungeonId or dungeonId == 0 then
        return -- not the final encounter
    end
    local name = DUNGEONS[dungeonId]
    if not name then
        return -- raid, UBRS or holiday content
    end
    local players = map:GetPlayers()
    if not players or #players ~= 1 then
        return -- not solo (bots in the instance count as players)
    end
    local player = players[1]
    if IsBot(player) then
        return
    end
    local clears = Clears(player)
    if clears.set[dungeonId] then
        return -- already recorded (re-kills in the same instance included)
    end
    clears.set[dungeonId] = true
    clears.count = clears.count + 1
    CharDBExecute("INSERT IGNORE INTO `" .. Constant.DB_NAME
        .. "`.`paragon_solo_clears` (guid, dungeon) VALUES ("
        .. player:GetGUIDLow() .. ", " .. dungeonId .. ");")
    player:SendBroadcastMessage(string.format(
        "|cffffd100[Paragon]|r Solo clear recorded: %s (%d/%d)",
        name, clears.count, TOTAL))
    -- granted here rather than only via Reconcile so the achievement
    -- lands for any human, including below the level/paragon gates
    pcall(ReconcileAchievements, player, clears)
    SafeReconcile(player, false, "clear")
end

RegisterServerEvent(ENCOUNTER_EVENT, function(...)
    local ok, err = pcall(OnEncounterComplete, ...)
    if not ok then
        print("[Paragon] solo dungeon encounter error: " .. tostring(err))
    end
end)

