--[[
    Paragon Rework: solo dungeon clears (milestone 1200, universal)

    Every unique 5-man dungeon the character clears SOLO grants +2
    resilience rating and +0.25% critical strike damage (applied in whole
    percents: every 4 clears = +1%, by design — aura 163 amounts are
    integer percent). Each dungeon counts once, the first time its final
    encounter completes with the character alone in the instance; heroic
    versions are separate dungeons. 92 dungeons total.

    Detection: the §1p ALE hook MAP_EVENT_ON_ENCOUNTER_COMPLETE (server
    event 36) mirrors GlobalScript::OnAfterUpdateEncounterState — the
    core's own completion matcher in Map::UpdateEncounterState. It fires
    for BOTH credit types (boss kill and scripted spell credit: Culling of
    Stratholme, Drak'Tharon, Trial of the Champion, Halls of Reflection)
    with dungeonId = instance_encounters.lastEncounterDungeon, non-zero
    exactly when the FINAL encounter of (map, difficulty) was credited.
    No boss AI is replaced (RegisterCreatureEvent would hijack scripted
    AIs) and no InstanceScript is displaced.

    Solo check: map:GetPlayers() at credit time must contain exactly one
    player. Playerbots are real Player objects in the map's player list,
    so a bot inside the instance breaks solo — being in a group with
    players OUTSIDE the instance does not (nobody helped). Dungeon maps
    are per-instance objects, so the list is this run only.

    The DUNGEONS table is the allowlist (raids, UBRS and holiday bosses
    have final encounters too — absent ids never record) AND the display
    name source: the DB cannot map LFG dungeon ids to names (lfgdungeons_dbc
    is an empty override table), so the 92 ids are enumerated here from
    the instance_encounters census.

    Clears are recorded for any human character from module install on
    (no retroactivity — past clears carry no solo/group record); the
    milestone gates the STATS, not the registry, so progress made before
    reaching 1200 counts once the milestone unlocks.

    Accepted windows (all mirror core LFG-completion semantics):
      - a solo player who dies and RELEASES before the credit lands is
        outside the map at count time — that run records nothing (the run
        is repeatable after an instance reset);
      - Halls of Reflection credits ~19s into the escape outro (72830 is
        cast by the escort at UpdateOutro step 5) — leaving during the
        outro forfeits that run;
      - kill-credit finals follow core loot eligibility: the player (or
        their pets) must deal >= 50% of the boss's max health or the core
        never reaches KillRewarder (scripted allies soloing the boss for
        you records nothing).

    Crit damage carrier: server-only spell 1900118 (aura 163
    SPELL_AURA_MOD_CRIT_DAMAGE_BONUS, misc 127 = all schools) affects
    melee white crits, melee/ranged special + Auto Shot crits and all
    spell crits — not healing crits, mirroring the stock Chaotic Skyflare
    meta. bp passes through CastCustomSpell exactly (die 0); recast with a
    new bp rewrites the live aura. Same reconcile-owning-carrier rules as
    the gem-double mp5 aura: own spell id, ReconcileCrit runs on every
    eligible reconcile (the aura is death-persistent — a stale copy must
    be cleared at relog when nothing is owed).

    Tooltip: prefix "ParagonSolo" fn 1 pushes { count, total, resil,
    crit, next_at }; Paragon_RewardTrack.lua renders the live numbers
    under the milestone-1200 track node.

    Achievements (96, own "Solo Clears" subtab under Dungeons & Raids):
    one per dungeon (id 19000 + LFG dungeon id), three era metas
    (19301-03) and the "Pinnacle" capstone (19304, grants the Pinnacle
    title via achievement_reward). Rows are generated by
    Tools/paragon_client_patch.py into the client MPQ AND the
    acore_world achievement*_dbc override tables. The metas/capstone
    complete natively through type-8 COMPLETE_ACHIEVEMENT criteria
    chains; ReconcileAchievements below grants per-dungeon rows and
    doubles as the retro-grant for clears banked before the rows
    existed. Grants are unrelated to the milestone — the registry earns
    them, so achievements accrue below paragon 1200.
]]

