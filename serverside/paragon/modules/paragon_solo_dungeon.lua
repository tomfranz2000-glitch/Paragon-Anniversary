RegisterMediatorEvent("OnAfterClientLoadRequest", function(player, paragon)
    if player then
        SafeReconcile(player, true, "load")
    end
end)

RegisterMediatorEvent("OnParagonLevelChanged", function(player, paragon)
    if player then
        SafeReconcile(player, false, "level")
    end
end)

-- ReloadALE wipes the session store (APPLIED_KEY) while the rating mods
-- persist on live Player objects — the next reconcile would then stack a
-- second copy. Unapply before the state closes (event 16 fires before
-- lua_close, GetData still readable); the crit aura needs nothing, since
-- ReconcileCrit self-heals via HasAura.
RegisterServerEvent(16, function()
    local players = GetPlayersInWorld()
    if not players then
        return
    end
    for _, player in pairs(players) do
        local prev = player:GetData(APPLIED_KEY) or 0
        if prev > 0 then
            pcall(ApplyResil, player, prev, false)
        end
    end
end)

